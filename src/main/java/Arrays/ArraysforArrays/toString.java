package Arrays.ArraysforArrays;

import java.util.Arrays;

public class toString {
    public static void main(String[] args) {
        int arr[]={1,2,3,4,5,6,7,8};

        System.out.println(arr); // it gives unreadable formate of created arrays
        System.out.println(Arrays.toString(arr)); // toString provides the readable formate of arrays
    }


}
